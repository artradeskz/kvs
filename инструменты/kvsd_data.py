def translate_operand(operand):
    """
    Переводит операнд: заменяет все регистры на кастомные имена.
    Также удаляет слово "short" из операндов.
    """
    if not operand:
        return operand
    
    result = operand
    
    # Удаляем "short" из операндов (для коротких переходов)
    result = result.replace("short ", "")
    result = result.replace(" short", "")
    
    # Сортируем регистры по длине (от длинных к коротким)
    sorted_regs = sorted(REGISTER_TRANSLATION.keys(), key=len, reverse=True)
    
    for reg in sorted_regs:
        trans_reg = REGISTER_TRANSLATION[reg]
        for sep in ['', ' ', ',', '+', '-', '*', '/', '(', ')', '[', ']', ':', '&', '|']:
            result = result.replace(reg + sep, trans_reg + sep)
            result = result.replace(sep + reg, sep + trans_reg)
        if result.startswith(reg):
            result = trans_reg + result[len(reg):]
        if result.endswith(reg):
            result = result[:-len(reg)] + trans_reg
        result = result.replace(reg, trans_reg)
    
    return result


def translate_line(line):
    """
    Переводит строку дизассемблера.
    Формат: "00401000  48B80A0000000000  mov rax,0xa"
    """
    if not line.strip():
        return line
    
    parts = line.split(maxsplit=2)
    if len(parts) < 3:
        return line
    
    address = parts[0]
    bytes_hex = parts[1]
    rest = parts[2]
    
    rest_parts = rest.split(maxsplit=1)
    mnemonic = rest_parts[0]
    operands = rest_parts[1] if len(rest_parts) > 1 else ""
    
    # Вычисляем длину инструкции
    instr_len = len(bytes_hex) // 2 if bytes_hex else 0
    
    new_mnemonic = translate_mnemonic(mnemonic, operands, instr_len)
    new_operands = translate_operand(operands)
    
    if new_operands:
        return f"{address}  {bytes_hex}  {new_mnemonic} {new_operands}"
    else:
        return f"{address}  {bytes_hex}  {new_mnemonic}"